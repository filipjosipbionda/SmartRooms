internal object KnowledgeCatalog {
    fun itemsFor(
        cefrLevel: String,
        quizKind: QuizKind,
    ): List<KnowledgeCatalogItem> =
        items.filter { item ->
            item.cefrLevel.equals(cefrLevel.trim(), ignoreCase = true) &&
                item.quizKind == quizKind
        }

    fun itemById(id: String): KnowledgeCatalogItem? = items.firstOrNull { it.id == id }

    private fun grammar(
        level: String,
        category: String,
        title: String,
    ): KnowledgeCatalogItem =
        KnowledgeCatalogItem(
            id = "${level.lowercase()}_grammar_${title.toCatalogId()}",
            cefrLevel = level,
            quizKind = QuizKind.GRAMMAR,
            category = category,
            title = title,
        )

